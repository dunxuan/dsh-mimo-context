export class Store {
  constructor(config_, logger) {
    this.config = config_
    this.logger = logger
    this.home = process.env.DSH_HOME && process.env.DSH_HOME.trim().length > 0
      ? resolve(process.env.DSH_HOME)
      : join(homedir(), '.dsh')
    this.root = this.config.storageDir && this.config.storageDir.length > 0
      ? resolve(this.config.storageDir)
      : join(this.home, 'mimo-context')
  }

  /** Legacy workspace-scoped directory (pre-MiMo-layout installs). */
  legacyDir(cwd) {
    const normalized = normalizeCwd(cwd)
    if (this.config.storage.workspace) return join(normalized, '.mimo-context')
    return join(this.root, 'workspaces', sha1(normalized).slice(0, 16))
  }

  paths(cwdOrScope, maybeSessionId) {
    const { cwd, sessionId } = normalizeScope(cwdOrScope, maybeSessionId)
    const projectKey = sha1(cwd).slice(0, 16)
    const projectDir = join(this.root, 'projects', projectKey)
    const globalDir = join(this.root, 'global')
    if (this.config.storage.layout === 'workspace') {
      const dir = this.legacyDir(cwd)
      return {
        layout: 'workspace',
        cwd,
        projectKey,
        sessionId: sessionId ?? 'workspace',
        dir,
        sessionDir: dir,
        projectDir: dir,
        globalDir,
        checkpoint: join(dir, 'checkpoint.md'),
        memory: join(dir, 'MEMORY.md'),
        notes: join(dir, 'notes.md'),
        tasks: join(dir, 'tasks'),
        skills: join(dir, 'skills'),
        prev: join(dir, '.prev'),
        meta: join(dir, 'meta.json'),
        globalMemory: join(globalDir, 'MEMORY.md'),
        projectMeta: join(dir, 'project.json'),
      }
    }
    const sessionKey = safeId(sessionId ?? 'session')
    const sessionDir = join(this.root, 'sessions', sessionKey)
    return {
      layout: 'mimo',
      cwd,
      projectKey,
      sessionId: sessionId ?? 'session',
      dir: sessionDir,
      sessionDir,
      projectDir,
      globalDir,
      checkpoint: join(sessionDir, 'checkpoint.md'),
      memory: join(projectDir, 'MEMORY.md'),
      notes: join(sessionDir, 'notes.md'),
      tasks: join(sessionDir, 'tasks'),
      skills: join(projectDir, 'skills'),
      prev: join(sessionDir, '.prev'),
      meta: join(sessionDir, 'meta.json'),
      globalMemory: join(globalDir, 'MEMORY.md'),
      projectMeta: join(projectDir, 'project.json'),
    }
  }

  ensure(cwdOrScope, maybeSessionId) {
    const paths = this.paths(cwdOrScope, maybeSessionId)
    for (const path of [paths.sessionDir, paths.projectDir, paths.tasks, paths.skills, paths.prev, paths.globalDir]) {
      mkdirSync(path, { recursive: true })
    }
    // Migrate before scaffolding templates so a legacy file wins over a fresh
    // template (copyIfMissing would otherwise see the template and skip it).
    if (paths.layout === 'mimo') this.migrateLegacy(paths)
    // MiMo memory.disable_write / MIMOCODE_DISABLE_CHECKPOINT stop producing NEW
    // memory, including the template bootstrap. Reads still work (missing files
    // are treated as empty) and existing files stay readable.
    const bootstrap = this.config.memoryWrite !== false && this.config.checkpointEnabled !== false
    if (bootstrap) {
      if (!existsSync(paths.checkpoint)) atomicWrite(paths.checkpoint, CHECKPOINT_TEMPLATE)
      if (!existsSync(paths.memory)) atomicWrite(paths.memory, MEMORY_TEMPLATE)
      if (!existsSync(paths.notes)) atomicWrite(paths.notes, NOTES_TEMPLATE)
      if (!existsSync(paths.projectMeta)) {
        atomicWrite(paths.projectMeta, JSON.stringify({ cwd: paths.cwd, createdAt: nowIso() }, null, 2))
      }
    }
    return paths
  }

  /** One-time copy of the old workspace layout into the MiMo session/project layout. */
  migrateLegacy(paths) {
    try {
      const legacy = this.legacyDir(paths.cwd)
      if (!existsSync(legacy) || legacy === paths.sessionDir) return
      copyIfMissing(join(legacy, 'checkpoint.md'), paths.checkpoint)
      copyIfMissing(join(legacy, 'notes.md'), paths.notes)
      copyIfMissing(join(legacy, 'MEMORY.md'), paths.memory)
      for (const name of ['tasks', 'skills']) {
        const sourceDir = join(legacy, name)
        const targetDir = name === 'tasks' ? paths.tasks : paths.skills
        try {
          for (const entry of readdirSync(sourceDir, { withFileTypes: true })) {
            if (entry.isFile()) copyIfMissing(join(sourceDir, entry.name), join(targetDir, entry.name))
            else if (entry.isDirectory()) {
              for (const file of readdirSync(join(sourceDir, entry.name), { withFileTypes: true })) {
                if (file.isFile()) copyIfMissing(join(sourceDir, entry.name, file.name), join(targetDir, entry.name, file.name))
              }
            }
          }
        } catch {}
      }
      const legacyMeta = readTextIfExists(join(legacy, 'meta.json'))
      if (legacyMeta !== undefined && !existsSync(paths.meta)) {
        try {
          atomicWrite(paths.meta, legacyMeta)
        } catch {}
      }
    } catch {}
  }

  meta(cwdOrScope, maybeSessionId) {
    const paths = this.paths(cwdOrScope, maybeSessionId)
    const raw = readTextIfExists(paths.meta)
    if (raw === undefined) return {}
    try {
      return JSON.parse(raw)
    } catch {
      return {}
    }
  }

  setMeta(cwdOrScope, patch, maybeSessionId) {
    const paths = this.paths(cwdOrScope, maybeSessionId)
    const meta = { ...this.meta(cwdOrScope, maybeSessionId), ...patch }
    atomicWrite(paths.meta, JSON.stringify(meta, null, 2))
    return meta
  }

  read(cwdOrScope, maybeSessionId) {
    const paths = this.ensure(cwdOrScope, maybeSessionId)
    const checkpoint = readTextIfExists(paths.checkpoint) ?? ''
    const memory = readTextIfExists(paths.memory) ?? ''
    const notes = readTextIfExists(paths.notes) ?? ''
    const globalMemory = readTextIfExists(paths.globalMemory) ?? ''
    const meta = this.meta(cwdOrScope, maybeSessionId)
    const generation = sha1(`${checkpoint}\n---\n${memory}\n---\n${notes}`)
    const checkpointWritten = checkpoint.trim().length > 0 && checkpoint.trim() !== CHECKPOINT_TEMPLATE.trim()
    const memoryWritten = memory.trim().length > 0 && memory.trim() !== MEMORY_TEMPLATE.trim()
    const watermark = Number.isFinite(meta.lastCheckpointSeq) ? meta.lastCheckpointSeq : undefined
    return {
      paths,
      checkpoint,
      memory,
      notes,
      globalMemory,
      meta,
      generation,
      // MiMo `hasCheckpoint` is a bare exists(); a USABLE checkpoint additionally
      // needs the watermark advanced by a successful writer. Legacy installs did
      // not record a watermark, so a non-template file counts as usable.
      hasCheckpoint: checkpointWritten,
      hasUsableCheckpoint: watermark !== undefined || (checkpointWritten && (meta.writerCalls ?? 0) > 0),
      hasMemory: memoryWritten,
      watermark,
    }
  }

  writeCheckpoint(cwdOrScope, checkpointText, memoryText, metaPatch = {}, options = {}) {
    const paths = this.ensure(cwdOrScope)
    return withFileLockSync(join(paths.projectDir, '.MEMORY.lock'), () => {
      const previous = this.read(cwdOrScope)
      const currentMemory = readTextIfExists(paths.memory) ?? ''
      let memory = truncateBytes(memoryText ?? previous.memory, this.config.storage.maxMemoryBytes)
      let memorySkipped = false
      if (options.expectedMemoryHash !== undefined && sha1(currentMemory) !== options.expectedMemoryHash) {
        // Another session wrote this project's MEMORY while our writer was
        // running. Keep the newer body instead of silently clobbering it; the
        // session checkpoint itself is still persisted.
        memory = currentMemory
        memorySkipped = true
      }
      const checkpoint = truncateBytes(checkpointText, this.config.storage.maxCheckpointBytes)
      if (previous.checkpoint.trim().length > 0) atomicWrite(join(paths.prev, 'checkpoint.md'), previous.checkpoint)
      if (previous.memory.trim().length > 0) atomicWrite(join(paths.prev, 'MEMORY.md'), previous.memory)
      atomicWrite(paths.checkpoint, checkpoint)
      atomicWrite(paths.memory, memory)
      const generation = sha1(`${checkpoint}\n---\n${memory}\n---\n${previous.notes}`)
      const meta = this.setMeta(cwdOrScope, {
        generation,
        updatedAt: nowIso(),
        checkpointTokens: estimateTokens(checkpoint),
        memoryTokens: estimateTokens(memory),
        ...(memorySkipped ? { memoryMergeSkipped: true } : {}),
        ...metaPatch,
      })
      return { checkpoint, memory, generation, meta, paths, memorySkipped }
    })
  }

  writeMemory(cwdOrScope, memoryText, patch = {}) {
    const paths = this.ensure(cwdOrScope)
    return withFileLockSync(join(paths.projectDir, '.MEMORY.lock'), () => {
      const previous = readFileSync(paths.memory, 'utf8')
      if (previous.trim().length > 0) atomicWrite(join(paths.prev, 'MEMORY.md'), previous)
      const memory = truncateBytes(memoryText, this.config.storage.maxMemoryBytes)
      atomicWrite(paths.memory, memory)
      const checkpoint = readFileSync(paths.checkpoint, 'utf8')
      const notes = readFileSync(paths.notes, 'utf8')
      const generation = sha1(`${checkpoint}\n---\n${memory}\n---\n${notes}`)
      this.setMeta(cwdOrScope, { generation, updatedAt: nowIso(), memoryUpdatedAt: nowIso(), ...patch })
      return { memory, generation, paths }
    })
  }

  writeNotes(cwdOrScope, content) {
    const paths = this.ensure(cwdOrScope)
    const notes = truncateBytes(content, this.config.storage.maxNotesBytes)
    atomicWrite(paths.notes, notes)
    return notes
  }

  resetNotes(cwdOrScope) {
    const paths = this.ensure(cwdOrScope)
    atomicWrite(paths.notes, NOTES_TEMPLATE)
    return NOTES_TEMPLATE
  }

  appendNotes(cwdOrScope, content, turn) {
    const paths = this.ensure(cwdOrScope)
    const previous = readFileSync(paths.notes, 'utf8')
    const addition = String(content ?? '').trim()
    if (!addition) return previous
    // MiMo notes entry format: `## [turn N · YYYY-MM-DDTHH:MM:SSZ]`.
    const stamp = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z').slice(0, 19) + 'Z'
    const heading = turn === undefined ? `## [${stamp}]` : `## [turn ${turn} · ${stamp}]`
    const next = `${previous.trimEnd()}\n\n${heading}\n${addition}\n`
    return this.writeNotes(cwdOrScope, next)
  }

  writeTaskProgress(cwdOrScope, taskId, content) {
    const paths = this.ensure(cwdOrScope)
    const id = safeId(taskId)
    const dir = join(paths.tasks, id)
    mkdirSync(dir, { recursive: true })
    atomicWrite(join(dir, 'progress.md'), String(content ?? ''))
    return join(dir, 'progress.md')
  }

  taskSummaries(cwdOrScope, maxPerTaskChars = 1500) {
    const paths = this.ensure(cwdOrScope)
    const result = []
    let entries = []
    try {
      entries = readdirSync(paths.tasks, { withFileTypes: true })
    } catch {
      return result
    }
    for (const entry of entries) {
      if (!entry.isDirectory()) continue
      const file = join(paths.tasks, entry.name, 'progress.md')
      if (!existsSync(file)) continue
      const text = readFileSync(file, 'utf8').trim()
      if (!text) continue
      result.push({ id: entry.name, text: text.slice(0, maxPerTaskChars) })
    }
    return result
  }

  writeSkill(cwdOrScope, name, content) {
    const paths = this.ensure(cwdOrScope)
    const safeName = String(name).replace(/[^A-Za-z0-9._-]/g, '-').replace(/^-+|-+$/g, '').slice(0, 80) || 'skill'
    const file = join(paths.skills, `${safeName}.md`)
    atomicWrite(file, String(content ?? ''))
    return file
  }

  skills(cwdOrScope) {
    const paths = this.ensure(cwdOrScope)
    try {
      return readdirSync(paths.skills)
        .filter((name) => name.endsWith('.md'))
        .map((name) => ({ name: name.slice(0, -3), path: join(paths.skills, name) }))
    } catch {
      return []
    }
  }

  globalMemory(cwdOrScope) {
    const paths = this.paths(cwdOrScope)
    return readTextIfExists(paths.globalMemory) ?? ''
  }

  projectMemory(cwdOrScope) {
    const paths = this.ensure(cwdOrScope)
    return readTextIfExists(paths.memory) ?? ''
  }

  stats(cwdOrScope) {
    const state = this.read(cwdOrScope)
    return {
      dir: state.paths.sessionDir,
      projectDir: state.paths.projectDir,
      checkpointTokens: estimateTokens(state.checkpoint),
      memoryTokens: estimateTokens(state.memory),
      globalMemoryTokens: estimateTokens(state.globalMemory),
      notesTokens: estimateTokens(state.notes),
      tasks: this.taskSummaries(cwdOrScope).length,
      skills: this.skills(cwdOrScope).length,
      generation: state.generation,
      updatedAt: state.meta.updatedAt ?? null,
      writerCalls: state.meta.writerCalls ?? 0,
      rebuilds: state.meta.rebuilds ?? 0,
      watermark: state.watermark ?? null,
    }
  }
}

