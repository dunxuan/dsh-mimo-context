// File-backed MiMo memory store.
//
// MiMo layout (packages/cli/src/session/checkpoint-paths.ts, checkpoint-templates.ts):
//   <root>/sessions/<sessionID>/checkpoint.md   (writer-owned, 11 sections)
//   <root>/sessions/<sessionID>/notes.md        (main agent scratchpad)
//   <root>/sessions/<sessionID>/tasks/<TID>/progress.md
//   <root>/projects/<projectID>/MEMORY.md       (writer/main-owned, 4 sections)
//   <root>/global/MEMORY.md                     (user-owned, read-only to agents)
//
// DSH has no separate project ID; the normalized cwd hash is the project key and
// `agent.session.id` is the session key. A legacy workspace-scoped layout is
// migrated on first use.
//
// All writes are atomic and keep a `.prev/` copy of the session checkpoint and
// project memory.

