export function readBudgetedText(filePath, budgetTokens) {
  const fullText = readTextIfExists(filePath)
  if (fullText === undefined) return undefined
  const totalTokens = estimateTokens(fullText)
  if (totalTokens <= budgetTokens) return { text: fullText, truncated: false, totalTokens }
  const ratio = budgetTokens / totalTokens
  let truncatedText = fullText.slice(0, Math.floor(fullText.length * ratio * 0.95))
  const lastNewline = truncatedText.lastIndexOf('\n')
  if (lastNewline > 0) truncatedText = truncatedText.slice(0, lastNewline)
  const hint = `\n\n⚠️ Truncated at ~${budgetTokens} tokens. ${filePath} is ~${totalTokens} tokens total. read("${filePath}", offset=${truncatedText.length}) for the rest.`
  return { text: truncatedText + hint, truncated: true, totalTokens }
}

function parseMarkdownSections(text) {
  const preamble = []
  const sections = []
  let current = null
  let italicSeen = false
  for (const line of String(text).split('\n')) {
    if (line.startsWith('## ')) {
      if (current) sections.push(current)
      current = { header: line, italic: '', body: [], indexLines: [] }
      italicSeen = false
      continue
    }
    if (current) {
      if (!italicSeen && line.startsWith('_') && line.endsWith('_')) {
        current.italic = line
        italicSeen = true
        continue
      }
      if (/^- See \S+\.md \(\d+/.test(line.trim())) current.indexLines.push(line)
      current.body.push(line)
    } else {
      preamble.push(line)
    }
  }
  if (current) sections.push(current)
  return { preamble, sections }
}

export function readBudgetedSectionAwareText(text, budgetTokens, label = 'memory file') {
  if (typeof text !== 'string' || text.length === 0) return undefined
  const totalTokens = estimateTokens(text)
  if (totalTokens <= budgetTokens) return { text, truncated: false, totalTokens }
  const { preamble, sections } = parseMarkdownSections(text)
  const headerOnlyTokens = estimateTokens([...preamble, ...sections.flatMap((section) => [section.header, section.italic, ...section.indexLines])].join('\n'))
  if (headerOnlyTokens >= budgetTokens) {
    const skeleton = [...preamble, ...sections.flatMap((section) => [section.header, section.italic, ...section.indexLines, ''])].join('\n')
    return {
      text: `${skeleton}\n\n⚠️ File extremely large (${totalTokens} tokens vs budget ${budgetTokens}). Only structure shown.\n   read("${label}") for full content.`,
      truncated: true,
      totalTokens,
    }
  }
  const out = [...preamble]
  let used = estimateTokens(out.join('\n'))
  for (const section of sections) {
    used += estimateTokens([section.header, section.italic, ...section.indexLines].join('\n'))
    out.push(section.header, section.italic, ...section.indexLines)
    const body = section.body.filter((line) => !section.indexLines.includes(line)).join('\n')
    const bodyTokens = estimateTokens(body)
    if (used + bodyTokens <= budgetTokens) {
      out.push(body)
      used += bodyTokens
    } else {
      const remaining = budgetTokens - used
      if (remaining > 50) {
        const cutLength = Math.floor(body.length * (remaining / Math.max(1, bodyTokens)) * 0.95)
        out.push(body.slice(0, cutLength))
        used += remaining
      }
    }
    out.push('')
  }
  return {
    text: `${out.join('\n')}\n\n⚠️ Truncated at ~${budgetTokens} tokens. ${label} is ~${totalTokens} tokens total. read("${label}") for full content.`,
    truncated: true,
    totalTokens,
  }
}

