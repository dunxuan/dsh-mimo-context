function normalizeCwd(cwd) {
  return resolve(cwd || process.cwd())
}

function safeId(value) {
  return String(value || 'global').replace(/[^A-Za-z0-9._-]/g, '_').slice(0, 120) || 'global'
}

function normalizeScope(cwdOrScope, maybeSessionId) {
  if (cwdOrScope !== null && typeof cwdOrScope === 'object') {
    return { cwd: normalizeCwd(cwdOrScope.cwd), sessionId: cwdOrScope.sessionId === undefined ? undefined : safeId(cwdOrScope.sessionId) }
  }
  return { cwd: normalizeCwd(cwdOrScope), sessionId: maybeSessionId === undefined ? undefined : safeId(maybeSessionId) }
}

function copyIfMissing(source, target) {
  try {
    if (!existsSync(source) || existsSync(target)) return false
    mkdirSync(dirname(target), { recursive: true })
    copyFileSync(source, target)
    return true
  } catch {
    return false
  }
}

